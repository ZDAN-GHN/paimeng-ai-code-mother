CREATE TABLE IF NOT EXISTS ts_snowflake_state (
 nodeId SMALLINT UNSIGNED PRIMARY KEY,
 lastId BIGINT UNSIGNED NOT NULL
);
INSERT INTO ts_snowflake_state(nodeId,lastId)
SELECT 0, COALESCE(MAX(id),0) FROM (
 SELECT id FROM user UNION ALL SELECT id FROM app UNION ALL SELECT id FROM chat_history
) AS existing_ids
WHERE id <= 9223372036854775807 AND ((id >> 12) & 1023) = 0
ON DUPLICATE KEY UPDATE lastId=GREATEST(lastId,VALUES(lastId));
ALTER TABLE user MODIFY COLUMN id BIGINT UNSIGNED NOT NULL;
ALTER TABLE app MODIFY COLUMN id BIGINT UNSIGNED NOT NULL;
ALTER TABLE chat_history MODIFY COLUMN id BIGINT UNSIGNED NOT NULL;
