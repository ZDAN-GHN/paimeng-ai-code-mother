import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
const root=resolve(import.meta.dirname,'../..');
const diff=execFileSync('git',['diff','--binary','--','.',':!refactor-ts-agent'],{cwd:root,maxBuffer:16*1024*1024});
const actual=createHash('sha256').update(diff).digest('hex');
const expected='8da2ce3cd0b356bf36752cc15686345abfc25d7579b4ec8562adbbb76b22a343';
if(actual!==expected) throw new Error('目录外已跟踪文件的差异与开始重构时不同');
const untracked=execFileSync('git',['ls-files','--others','--exclude-standard'],{cwd:root}).toString().trim().split('\n').filter(Boolean);
if(untracked.some(p=>!p.startsWith('refactor-ts-agent/'))) throw new Error('存在目录外未跟踪文件，请核对是否为用户改动');
console.log('旧 Java、Vue 与目录外已有差异保持不变');
